ROOT = Path(__file__).resolve().parent.parent
LIMITATIONS = [
    "Predicted attacks are unverified alerts, not confirmed incidents.",
    "No accuracy, precision, recall or false-positive rate without reviewed labels.",
    "Packet lengths, headers, subflows and active/idle boundaries remain approximations; "
    "this extractor has not been validated column-by-column against CICFlowMeter.",
    "Rules use finalized flows and their end timestamps, not packet-level windows. "
    "Rule hits mark only the triggering flow, not all earlier flows in a campaign.",
    "Partial sessions, encrypted traffic, packet loss and capture location affect features. "
    "Driver-level packet loss is not measured.",
    "End-of-file flush can contain incomplete flows. Inference timing excludes "
    "capture waiting, flow expiration, database writes and browser delivery.",
]


def dump_json(path, value):
    Path(path).write_text(json.dumps(value, ensure_ascii=False, indent=2,
                                    allow_nan=False) + "\n", encoding="utf-8")


def sha256(path):
    digest = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def positive_float(value):
    number = float(value)
    if not math.isfinite(number) or number <= 0:
        raise argparse.ArgumentTypeError("must be finite and positive")
    return number


def positive_int(value):
    number = int(value)
    if number <= 0:
        raise argparse.ArgumentTypeError("must be positive")
    return number


def create_output(path):
    if path is None:
        stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
        path = ROOT / "artifacts" / "traffic" / f"{stamp}-{uuid.uuid4().hex[:6]}"
    path = Path(path).resolve()
    path.mkdir(parents=True, exist_ok=False)
    return path


def capture_environment():
    from scapy.all import conf
    return {
        "python": sys.executable,
        "platform": platform.platform(),
        "use_pcap": bool(conf.use_pcap),
        "default_interface": str(conf.iface),
        "interfaces": [
            {"name": item.name, "description": item.description,
             "network_name": item.network_name, "ip": item.ip}
            for item in conf.ifaces.values()
        ],
    }


def capture_packets(output, interface, seconds, max_packets, bpf_filter):
    from scapy.all import PcapWriter, conf, sniff
    if sys.platform == "win32" and not conf.use_pcap:
        raise RuntimeError("Npcap unavailable. Install it manually, then retry in a new terminal.")
    selected = interface or str(conf.iface)
    path = output / "capture.pcap"
    count = 0
    started = time.perf_counter()
    with PcapWriter(str(path), sync=True) as writer:
        def record(pkt):
            nonlocal count
            writer.write(pkt)
            count += 1
        sniff(iface=selected, store=False, prn=record, timeout=seconds,
              count=max_packets, filter=bpf_filter, promisc=False)
    return path, {
        "interface": selected, "filter": bpf_filter,
        "requested_seconds": seconds,
        "elapsed_seconds": round(time.perf_counter() - started, 3),
        "packets_written": count, "packet_limit": max_packets,
        "packet_limit_reached": count >= max_packets,
        "promiscuous": False, "driver_drops": None,
    }


def analyze_pcap(path, output, provenance="unknown", source_note="",
                 idle_timeout=15.0, max_packets=20000, capture_info=None):
    from scapy.all import PcapReader
    import scapy
    import xgboost

    path = Path(path).resolve()
    input_hash = sha256(path)
    fixture = ROOT / "detector" / "samples" / "test_flows.pcap"
    if provenance == "real" and fixture.exists() and input_hash == sha256(fixture):
        raise ValueError("Bundled test_flows.pcap is synthetic, not real traffic")
    inf.load_model()
    run_id = uuid.uuid4().hex
    engine = DetectionEngine()
    extractor = FlowExtractor(idle_timeout)
    records = []
    packets = supported = 0
    first_ts = last_ts = None
    truncated = False
    peak_flows = 0
    started = time.perf_counter()

    def emit(features, meta, reason):
        features = {key: float(value) for key, value in features.items()}
        record = {"run_id": run_id, "flow_id": f"{run_id[:12]}-{len(records)+1:07d}",
                  **meta, "features": features, "finalization": reason}
        try:
            if not all(math.isfinite(v) for v in features.values()):
                raise ValueError("non-finite flow feature")
            record.update(engine.detect(features, meta))
            record["status"] = "ok"
        except Exception as exc:
            record.update(status="error", error=str(exc))
        records.append(record)

    with PcapReader(str(path)) as reader:
        for pkt in reader:
            if packets >= max_packets:
                truncated = True
                break
            ts = float(pkt.time)
            if not math.isfinite(ts) or (last_ts is not None and ts < last_ts):
                raise ValueError("PCAP timestamps must be finite and nondecreasing; "
                                 "do not score a silently reordered capture")
            if first_ts is None:
                first_ts = ts
            last_ts = ts
            packets += 1
            for features, meta in extractor.expire(now=ts):
                emit(features, meta, "idle_timeout")
            supported += int(extractor.process(pkt, ts=ts))
            peak_flows = max(peak_flows, extractor.size())
    for features, meta in extractor.expire(now=float("inf")):
        emit(features, meta, "end_of_capture")

    elapsed = time.perf_counter() - started
    valid = [row for row in records if row["status"] == "ok"]
    timings = [row["model_ms"] for row in valid]
    summary = {
        "schema_version": 1, "run_id": run_id,
        "created_at_utc": datetime.now(timezone.utc).isoformat(),
        "status": "empty" if not records else ("partial" if len(valid) != len(records) else "ok"),
        "provenance": provenance, "source_note": source_note,
        "input": {"filename": path.name, "sha256": input_hash},
        "model": {"filename": inf.MODEL_PATH.name, "sha256": sha256(inf.MODEL_PATH),
                  "meta_sha256": sha256(inf.META_PATH), "classes": inf._class_names},
        "feature_version": FEATURE_VERSION,
        "extractor_sha256": sha256(ROOT / "detector" / "flow_extractor.py"),
        "engine_sha256": sha256(ROOT / "detector" / "detection.py"),
        "runtime": {"python": platform.python_version(), "scapy": scapy.__version__,
                    "xgboost": xgboost.__version__, "numpy": np.__version__},
        "config": {"idle_timeout_seconds": idle_timeout, "max_packets": max_packets,
                   "scan_ports_exclusive": 15, "scan_window_seconds": 30,
                   "syn_count_exclusive": 100, "syn_window_seconds": 10},
        "capture": capture_info,
        "packets_read": packets, "ip_packets": supported,
        "non_ip_packets": packets - supported, "packet_limit_truncated": truncated,
        "first_packet_ts": first_ts, "last_packet_ts": last_ts,
        "observed_span_seconds": last_ts - first_ts if first_ts is not None else 0,
        "flows_total": len(records), "flows_scored": len(valid),
        "flow_errors": len(records) - len(valid), "peak_active_flows": peak_flows,
        "end_of_capture_flows": sum(row["finalization"] == "end_of_capture" for row in records),
        "prediction_distribution": dict(Counter(row["model"]["attack"] for row in valid)),
        "rule_hits": dict(Counter(hit["rule"] for row in valid for hit in row["rules"])),
        "alert_counts": {mode: sum(row[f"{mode}_alert"] for row in valid)
                         for mode in ("model", "rule", "combined")},
        "combined_alert_fraction": (sum(row["combined_alert"] for row in valid) / len(valid)
                                    if valid else None),
        "offline_processing_seconds": round(elapsed, 3),
        "model_inference_ms": {
            "p50": float(np.percentile(timings, 50)) if timings else None,
            "p95": float(np.percentile(timings, 95)) if timings else None,
            "max": max(timings) if timings else None,
        },
        "labeled_metrics": None, "limitations": LIMITATIONS,
    }
    with (output / "flows.jsonl").open("w", encoding="utf-8") as stream:
        for record in records:
            stream.write(json.dumps(record, ensure_ascii=False, allow_nan=False) + "\n")
    fields = ["run_id", "flow_id", "start_ts", "end_ts", "src_ip", "src_port", "dst_ip",
              "dst_port", "proto", "true_label", "label_basis", "reviewer"]
    with (output / "review.csv").open("w", newline="", encoding="utf-8-sig") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields, extrasaction="ignore")
        writer.writeheader()
        # Leave labels blank and omit model predictions to reduce review bias.
        writer.writerows(records)
    dump_json(output / "summary.json", summary)
    (output / "report.md").write_text(observation_markdown(summary), encoding="utf-8")
    return summary


def observation_markdown(summary):
    lines = ["# Traffic Observation", "", f"- Run: `{summary['run_id']}`",
             f"- Status: {summary['status']}; provenance: {summary['provenance']}",
             f"- Packets: {summary['packets_read']}; IP packets: {summary['ip_packets']}",
             f"- Flows: {summary['flows_total']}; prediction errors: {summary['flow_errors']}",
             f"- Observed span: {summary['observed_span_seconds']:.3f} seconds",
             f"- Input SHA256: `{summary['input']['sha256']}`", "",
             "## Unverified Decisions", "", "| Mode | Alerting flows |",
             "| --- | ---: |"]
    for mode, count in summary["alert_counts"].items():
        lines.append(f"| {mode} | {count} |")
    lines += ["", "| Predicted class | Flows |", "| --- | ---: |"]
    for name, count in summary["prediction_distribution"].items():
        lines.append(f"| {name} | {count} |")
    lines += ["", "## Interpretation", "",
              "No ground truth is available. Alert fraction is NOT a false-positive rate. "
              "Do not report these predictions as confirmed attacks or measured accuracy.", "",
              "Review `review.csv` using independent evidence, then use the score command. "
              "Leave uncertain labels blank; review normal predictions as well as alerts.", "",
              "## Limitations", ""]
    lines += [f"- {item}" for item in summary["limitations"]]
    return "\n".join(lines) + "\n"


def binary_metrics(truth, predicted):
    tp = sum(t and p for t, p in zip(truth, predicted))
    tn = sum(not t and not p for t, p in zip(truth, predicted))
    fp = sum(not t and p for t, p in zip(truth, predicted))
    fn = sum(t and not p for t, p in zip(truth, predicted))
    return {"tp": tp, "tn": tn, "fp": fp, "fn": fn,
            "precision": tp / (tp + fp) if tp + fp else None,
            "recall": tp / (tp + fn) if tp + fn else None,
            "f1": 2 * tp / (2 * tp + fp + fn) if 2 * tp + fp + fn else None,
            "false_positive_rate": fp / (fp + tn) if fp + tn else None,
            "accuracy": (tp + tn) / len(truth) if truth else None}


def score_run(run, labels_path):
    run = Path(run)
    summary = json.loads((run / "summary.json").read_text(encoding="utf-8"))
    records = [json.loads(line) for line in (run / "flows.jsonl").read_text(
        encoding="utf-8").splitlines() if line.strip()]
    by_id = {row["flow_id"]: row for row in records}
    classes = summary["model"]["classes"]
    reviewed = []
    seen = set()
    with Path(labels_path).open(encoding="utf-8-sig", newline="") as stream:
        reader = csv.DictReader(stream)
        required = {"run_id", "flow_id", "true_label", "label_basis", "reviewer"}
        if not required.issubset(reader.fieldnames or []):
            raise ValueError(f"Label CSV requires columns: {sorted(required)}")
        for row in reader:
            flow_id = row["flow_id"]
            if row["run_id"] != summary["run_id"] or flow_id not in by_id:
                raise ValueError(f"Label does not belong to this run: {flow_id}")
            if flow_id in seen:
                raise ValueError(f"Duplicate label row: {flow_id}")
            seen.add(flow_id)
            label = row["true_label"].strip()
            if not label:
                continue
            if label not in classes:
                raise ValueError(f"Unknown true_label {label!r}; use one of {classes}")
            if not row["label_basis"].strip() or not row["reviewer"].strip():
                raise ValueError(f"Evidence and reviewer required for {flow_id}")
            if by_id[flow_id]["status"] != "ok":
                raise ValueError(f"Prediction failed for reviewed flow {flow_id}; resolve before scoring")
            reviewed.append((label, by_id[flow_id]))
    if not reviewed:
        raise ValueError("No independently reviewed labels; accuracy cannot be calculated")
    truth = [label != "BENIGN" for label, _ in reviewed]
    matrix = [[0 for _ in classes] for _ in classes]
    for label, record in reviewed:
        matrix[classes.index(label)][classes.index(record["model"]["attack"])] += 1
    per_class = {}
    for i, label in enumerate(classes):
        tp = matrix[i][i]
        support = sum(matrix[i])
        predicted = sum(row[i] for row in matrix)
        per_class[label] = {"support": support,
                            "precision": tp / predicted if predicted else 0.0,
                            "recall": tp / support if support else 0.0,
                            "f1": 2 * tp / (support + predicted) if support + predicted else 0.0}
    supported = [row for row in per_class.values() if row["support"]]
    return {
        "run_id": summary["run_id"], "provenance": summary["provenance"],
        "labels_sha256": sha256(labels_path), "flows_sha256": sha256(run / "flows.jsonl"),
        "summary_sha256": sha256(run / "summary.json"),
        "flows_total": len(records), "reviewed_flows": len(reviewed),
        "label_coverage": len(reviewed) / len(records),
        "reviewed_benign": sum(not value for value in truth),
        "reviewed_attack": sum(truth), "flow_errors": summary["flow_errors"],
        "binary_ablation": {mode: binary_metrics(truth, [row[f"{mode}_alert"] for _, row in reviewed])
                            for mode in ("model", "rule", "combined")},
        "model_multiclass": {
            "classes": classes, "confusion_matrix_true_rows_predicted_columns": matrix,
            "per_class": per_class,
            "macro_f1_supported_classes": sum(row["f1"] for row in supported) / len(supported),
            "weighted_f1": sum(row["f1"] * row["support"] for row in supported) / len(reviewed),
        },
        "limitations": LIMITATIONS + [
            "Metrics cover reviewed rows only; selective review can bias all reported scores.",
            "Binary ablation is trigger-flow evaluation, not campaign-level recall. "
            "Model/combined alert overlap is counted once per flow.",
            "Undefined binary denominators are null; absent multiclass labels use zero "
            "and are excluded from supported-class macro-F1.",
            "Labels are user-reviewed, not independently certified by this tool. "
            "Synthetic/unknown provenance does not establish real-network performance.",
        ],
    }


def scoring_markdown(result):
    lines = ["# Reviewed Traffic Evaluation", "",
             f"Provenance: **{result['provenance']}**. "
             f"Reviewed {result['reviewed_flows']} / {result['flows_total']} flows.", "",
             "| Mode | TP | FP | TN | FN | Precision | Recall | F1 | FPR |",
             "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
    for mode, values in result["binary_ablation"].items():
        cells = [mode] + [str(values[k]) if k in ("tp", "fp", "tn", "fn")
                          else (f"{values[k]:.4f}" if values[k] is not None else "N/A")
                          for k in ("tp", "fp", "tn", "fn", "precision", "recall", "f1", "false_positive_rate")]
        lines.append("| " + " | ".join(cells) + " |")
    lines += ["", "Full multiclass confusion matrix and per-class metrics: `metrics.json`.", "",
              "## Limitations", ""] + [f"- {s}" for s in result["limitations"]]
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("doctor", help="Read capture driver and interface status")
    for name in ("observe", "pcap"):
        sub = commands.add_parser(name)
        sub.add_argument("--output", type=Path, help="New directory; existing paths are never overwritten")
        sub.add_argument("--idle-timeout", type=positive_float, default=15.0)
        sub.add_argument("--max-packets", type=positive_int, default=20000)
        sub.add_argument("--source-note", default="")
        if name == "observe":
            sub.add_argument("--interface", help="Default: Scapy's routing-selected interface")
            sub.add_argument("--seconds", type=positive_float, default=60.0)
            sub.add_argument("--filter", default="ip or ip6")
        else:
            sub.add_argument("path", type=Path)
            sub.add_argument("--provenance", choices=["real", "synthetic", "unknown"], default="unknown")
    score = commands.add_parser("score")
    score.add_argument("--run", required=True, type=Path)
    score.add_argument("--labels", required=True, type=Path)
    score.add_argument("--output", type=Path)
    args = parser.parse_args(argv)
    output = None
    try:
        if args.command == "doctor":
            print(json.dumps(capture_environment(), ensure_ascii=False, indent=2))
            return 0
        if args.command == "score":
            result = score_run(args.run, args.labels)
            output = create_output(args.output)
            dump_json(output / "metrics.json", result)
            (output / "report.md").write_text(scoring_markdown(result), encoding="utf-8")
        else:
            if args.command == "observe" and args.seconds > 600:
                raise ValueError("Observe is limited to 600 seconds per session")
            output = create_output(args.output)
            capture_info = None
            if args.command == "observe":
                dump_json(output / "environment.json", capture_environment())
                path, capture_info = capture_packets(output, args.interface, args.seconds,
                                                     args.max_packets, args.filter)
                dump_json(output / "capture.json", capture_info)
                provenance = "real"
            else:
                path, provenance = args.path, args.provenance
            result = analyze_pcap(path, output, provenance, args.source_note,
                                  args.idle_timeout, args.max_packets, capture_info)
            print(json.dumps({k: result[k] for k in (
                "status", "provenance", "packets_read", "flows_total", "flow_errors",
                "prediction_distribution", "alert_counts")}, ensure_ascii=False))
        print(f"Report: {output / 'report.md'}")
        return 0
    except Exception as exc:
        if output is not None:
            dump_json(output / "failure.json", {"status": "failed", "error": str(exc)})
        print(f"Evaluation failed: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
